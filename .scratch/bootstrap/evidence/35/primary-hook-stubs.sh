#!/bin/sh
# Ticket 35 evidence: primary-hook.sh's verdicts and cleanup, checked against
# stub hooks. Each case builds a throwaway repository with a prek-shaped
# pre-commit shim, PREK="<toplevel>/.pixi/envs/default/bin/prek" as prek writes
# it, and a stub prek, then runs primary-hook.sh there. It asserts the exit
# status and message, and that HEAD, the index and the status are as they were
# and the probe file is gone; in the last case, where the hook moves HEAD
# itself, that the script left HEAD and the index alone. HOME is a directory in
# <work>, so no global git configuration applies. Writes only to <work>, needs
# no network, and runs on macOS or Linux. Exits 1 at the first case that does
# not behave as expected.
# Usage: sh primary-hook-stubs.sh <empty-work-dir> > primary-hook-stubs.txt 2>&1
set -eu
fail() { printf 'FAIL: %s\n' "$*"; exit 1; }
here=$(cd "$(dirname "$0")" && pwd -P)
script=$here/primary-hook.sh
work=${1:?usage: primary-hook-stubs.sh <empty-work-dir>}
mkdir -p "$work"; work=$(cd "$work" && pwd -P)
[ -z "$(ls -A "$work")" ] || fail "work dir $work is not empty"
sha() { if command -v sha256sum > /dev/null; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }
HOME=$work/home
mkdir "$HOME"
unset XDG_CONFIG_HOME
export HOME

printf 'date: %s\nhost: %s\ngit: %s\ncheckout: <checkout> at %s\nprimary-hook.sh sha256: %s\nprimary-hook-stubs.sh sha256: %s\n' \
  "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$(uname -sm)" "$(git --version)" "$(git -C "$here" rev-parse HEAD)" \
  "$(sha "$script")" "$(sha "$here/primary-hook-stubs.sh")"

repo() { # repo <dir>: a committed repository with src/ and an ignored .pixi/
  git init -q -b main "$1"
  git -C "$1" config user.name stub
  git -C "$1" config user.email stub@example.invalid
  printf '.pixi/\n' > "$1/.gitignore"
  mkdir "$1/src"
  printf 'pub fn main() {\n  Nil\n}\n' > "$1/src/stub.gleam"
  git -C "$1" add .gitignore src/stub.gleam
  git -C "$1" commit -qm initial
  mkdir -p "$1/.pixi/envs/default/bin"
}
shim() { # shim <repo> <prek-path>: the pre-commit hook prek install writes
  hook=$(git -C "$1" rev-parse --path-format=absolute --git-path hooks/pre-commit)
  cat > "$hook" << EOF
#!/bin/sh
# File generated by prek: https://github.com/j178/prek
# ID: 182c10f181da4464a3eec51b83331688

HERE="\$(cd "\$(dirname "\$0")" && pwd)"
PREK="$2"

# Check if the full path to prek is executable, otherwise fallback to PATH
if [ ! -x "\$PREK" ]; then
    PREK="prek"
fi

exec "\$PREK" hook-impl --hook-dir "\$HERE" --script-version 4 --hook-type=pre-commit -- "\$@"
EOF
  chmod +x "$hook"
}
stub() { # stub <repo> <body>: the prek the shim names
  printf '#!/bin/sh\n%s\n' "$2" > "$1/.pixi/envs/default/bin/prek"
  chmod +x "$1/.pixi/envs/default/bin/prek"
}
toplevel() { git -C "$1" rev-parse --show-toplevel; }
refusal='printf "gleam format check.......................................................Failed\n- hook id: gleam-format\n- exit code: 1\n\n  src/hook_probe.gleam\n  Error: These files have not been formatted\n"
exit 1'

n=0
check() { # check <name> <dir> <expected exit> <expected line>...
  n=$((n + 1))
  printf '\n== %s. %s\n' "$n" "$1"
  dir=$2
  want=$3
  shift 3
  head=$(git -C "$dir" rev-parse HEAD)
  before=$(git -C "$dir" status --porcelain --untracked-files=all)
  set +e; (cd "$dir" && sh "$script") > "$work/case-$n.raw" 2>&1; rc=$?; set -e
  sed "s|$work|<work>|g" "$work/case-$n.raw" > "$work/case-$n.log"
  sed '/./s/^/     /' "$work/case-$n.log"
  [ "$rc" -eq "$want" ] || fail "exit $rc, expected $want"
  printf 'ok   exit %s\n' "$rc"
  for line in "$@"; do
    grep -qxF "$line" "$work/case-$n.log" || fail "no line reads '$line'"
    printf 'ok   the output has "%s"\n' "$line"
  done
  [ "$(git -C "$dir" rev-parse HEAD)" = "$head" ] || fail 'HEAD moved'
  git -C "$dir" diff --cached --quiet || fail 'the index is not clean'
  [ ! -e "$dir/src/hook_probe.gleam" ] || fail 'the probe file is still there'
  [ "$(git -C "$dir" status --porcelain --untracked-files=all)" = "$before" ] || fail 'git status changed'
  echo 'ok   HEAD, the index and the status are as they were, and no probe file is left'
}

r=$work/refused; repo "$r"; shim "$r" "$(toplevel "$r")/.pixi/envs/default/bin/prek"; stub "$r" "$refusal"
check 'the hook refuses the probe, by gleam format' "$r" 0 \
  'ok   gleam format refused the commit, naming src/hook_probe.gleam' 'primary-hook.sh: the hook refused the probe'

r=$work/accepting; repo "$r"; shim "$r" "$(toplevel "$r")/.pixi/envs/default/bin/prek"; stub "$r" 'exit 0'
# The EXIT trap undoes the commit, then checks HEAD, the index and the status itself.
check 'the hook accepts the probe' "$r" 1 'FAIL: the hook accepted the probe; undoing its commit' \
  'ok   git status is as it was'
grep -q '^ok   undid the probe commit [0-9a-f]\{40\}$' "$work/case-$n.log" || fail 'the trap did not report the undone commit'
echo 'ok   the trap reports the probe commit it undid'

r=$work/other-reason; repo "$r"; shim "$r" "$(toplevel "$r")/.pixi/envs/default/bin/prek"; stub "$r" 'exit 127'
check 'the hook refuses the probe for another reason' "$r" 1 'FAIL: the commit was refused, but not by gleam format'

r=$work/missing; repo "$r"; stub "$r" 'exit 0'
rm -f "$(git -C "$r" rev-parse --path-format=absolute --git-path hooks/pre-commit)"
check 'no pre-commit hook is installed' "$r" 2 'FAIL: no executable hook at <checkout>/.git/hooks/pre-commit; nothing was touched'

# The shim names an accepting prek in another checkout, so only the precondition stops the commit.
o=$work/other-checkout; repo "$o"; stub "$o" 'exit 0'
r=$work/elsewhere; repo "$r"; shim "$r" "$(toplevel "$o")/.pixi/envs/default/bin/prek"; stub "$r" "$refusal"
check "the hook runs another checkout's prek" "$r" 2 'FAIL: the hook runs PREK=<work>/other-checkout/.pixi/envs/default/bin/prek, not <checkout>/.pixi/envs/default/bin/prek; nothing was touched'

# A linked worktree resolves hooks/pre-commit to the primary's hook, which is valid here.
r=$work/primary; repo "$r"; shim "$r" "$(toplevel "$r")/.pixi/envs/default/bin/prek"; stub "$r" 'exit 0'
git -C "$r" worktree add -q "$work/linked" -b linked
check 'run from a linked worktree' "$work/linked" 2 'FAIL: this is a linked worktree; run from the primary checkout; nothing was touched'
[ "$(git -C "$r" status --porcelain --untracked-files=all)" = '' ] || fail 'the primary checkout changed'
echo 'ok   the primary checkout is untouched'

# The hook moves HEAD to a commit of its own and refuses: the script must not
# reset it, and leaves the probe staged for the maintainer to inspect.
n=$((n + 1))
printf '\n== %s. the hook moves HEAD to a commit that is not the probe'"'"'s\n' "$n"
r=$work/moved; repo "$r"; shim "$r" "$(toplevel "$r")/.pixi/envs/default/bin/prek"
# shellcheck disable=SC2016  # the stub expands it, not this script
stub "$r" 'git update-ref HEAD "$(git commit-tree -p HEAD -m other "HEAD^{tree}")"
exit 1'
head=$(git -C "$r" rev-parse HEAD)
set +e; (cd "$r" && sh "$script") > "$work/case-$n.raw" 2>&1; rc=$?; set -e
sed "s|$work|<work>|g" "$work/case-$n.raw" > "$work/case-$n.log"
sed '/./s/^/     /' "$work/case-$n.log"
[ "$rc" -eq 1 ] || fail "exit $rc, expected 1"
echo 'ok   exit 1'
moved=$(git -C "$r" rev-parse HEAD)
line="FAIL: HEAD moved to $moved, which is not the probe commit; HEAD, the index and src/hook_probe.gleam were left as they are"
grep -qxF "$line" "$work/case-$n.log" || fail "no line reads '$line'"
printf 'ok   the output has "%s"\n' "$line"
[ "$(git -C "$r" rev-parse HEAD^)" = "$head" ] || fail 'HEAD is not on top of the recorded HEAD'
[ "$(git -C "$r" log -1 --format=%s)" = other ] || fail 'HEAD is not the stub commit'
[ "$(git -C "$r" status --porcelain --untracked-files=all)" = 'A  src/hook_probe.gleam' ] || fail 'the probe is not left staged'
echo 'ok   HEAD is still the stub commit, and src/hook_probe.gleam is still staged'

printf '\nall %s cases passed\n' "$n"
